import { useState } from 'react';
import PropTypes from 'prop-types';
import { Link } from 'react-router';
import { useTranslation } from 'react-i18next';
import { CheckCircle2, ImageUp, Loader2, XCircle } from 'lucide-react';

import { API } from 'utils/api';
import { cn } from '@/lib/utils';
import { Alert, AlertDescription } from '@/components/ui/alert';
import { Button } from '@/components/ui/button';
import { SelectRow, TextRow, ToggleRow, splitLabelUnit } from '../parts';
import { settingEnumDescription, settingEnumLabel, settingLabel } from '@/components/settings/catalog';
import OptionCard, { bindSwitch } from './OptionCard';
import { settingsGroupUrl } from '../registry';

// ==============================|| PLATFORM SETTINGS — IMAGE STORAGE ||============================== //
// Where images generated by Gemini, Cloudflare Workers AI and Stability AI are uploaded, so a
// request that asks for an image URL gets one. By default the gateway keeps them itself for an
// hour on the site's address (common/media); off, those responses carry base64 instead. One
// storage is in use; "Test upload" tries the form as it stands, saved or not. Field labels, hints
// and help come from the settings catalog; the provider's hint is its value's description there.

const LOCAL = 'local';
const OFF = 'off';
const PROVIDERS = [LOCAL, 's3', 'alioss', 'smms', 'imgur', OFF];

// Text fields per provider: [option key, i18n field (for the placeholder), required, secret].
const FIELDS = {
  s3: [
    ['ImageStorageS3Endpoint', 's3Endpoint', true],
    ['ImageStorageS3Region', 's3Region'],
    ['ImageStorageS3BucketName', 'bucket', true],
    ['ImageStorageS3AccessKeyId', 'accessKeyId', true],
    ['ImageStorageS3AccessKeySecret', 'accessKeySecret', true, true],
    ['ImageStorageS3CDNURL', 's3CDNURL'],
    ['ImageStorageS3ExpirationDays', 's3ExpirationDays']
  ],
  alioss: [
    ['ImageStorageOSSEndpoint', 'ossEndpoint', true],
    ['ImageStorageOSSRegion', 'ossRegion'],
    ['ImageStorageOSSBucketName', 'bucket', true],
    ['ImageStorageOSSAccessKeyId', 'accessKeyId', true],
    ['ImageStorageOSSAccessKeySecret', 'accessKeySecret', true, true]
  ],
  smms: [['ImageStorageSMMSSecret', 'smmsSecret', true, true]],
  imgur: [['ImageStorageImgurClientId', 'imgurClientId', true, true]]
};

const PROVIDER_KEY = 'ImageStorageProvider';

// The body of POST /api/option/image_storage/test. Secret inputs are empty unless retyped: the
// server then uses the saved secret for the saved endpoint, bucket and key id.
export function imageStorageTestPayload(inputs) {
  const v = (k) => String(inputs[k] ?? '').trim();
  return {
    provider: v('ImageStorageProvider'),
    s3: {
      endpoint: v('ImageStorageS3Endpoint'),
      region: v('ImageStorageS3Region'),
      bucket_name: v('ImageStorageS3BucketName'),
      access_key_id: v('ImageStorageS3AccessKeyId'),
      access_key_secret: v('ImageStorageS3AccessKeySecret'),
      cdn_url: v('ImageStorageS3CDNURL'),
      expiration_days: Number(v('ImageStorageS3ExpirationDays')) || 0
    },
    alioss: {
      endpoint: v('ImageStorageOSSEndpoint'),
      region: v('ImageStorageOSSRegion'),
      bucket_name: v('ImageStorageOSSBucketName'),
      access_key_id: v('ImageStorageOSSAccessKeyId'),
      access_key_secret: v('ImageStorageOSSAccessKeySecret')
    },
    smms_secret: v('ImageStorageSMMSSecret'),
    imgur_client_id: v('ImageStorageImgurClientId')
  };
}

function UploadResult({ result }) {
  const { t } = useTranslation();
  if (!result) return null;
  return (
    <div
      role="status"
      className={cn(
        'flex items-start gap-3 rounded-md px-3 py-2 text-sm',
        result.ok ? 'bg-emerald-500/10 text-emerald-700 dark:text-emerald-400' : 'bg-destructive/10 text-destructive'
      )}
    >
      {result.ok ? <CheckCircle2 className="mt-0.5 size-4 shrink-0" /> : <XCircle className="mt-0.5 size-4 shrink-0" />}
      <div className="min-w-0 flex-1 space-y-2">
        <p className="break-words">{result.ok ? t('settingsUi.platform.imageStorage.test.ok') : result.message}</p>
        {result.ok && (
          <a href={result.url} target="_blank" rel="noreferrer" className="flex items-center gap-3 text-foreground hover:underline">
            <img src={result.url} alt="" className="size-10 shrink-0 rounded border border-border object-cover" />
            <span className="min-w-0 truncate font-mono text-xs">{result.url}</span>
          </a>
        )}
      </div>
    </div>
  );
}

UploadResult.propTypes = { result: PropTypes.object };

export default function ImageStorageCard({ ctx }) {
  const { t } = useTranslation();
  const s = (k, o) => t(`settingsUi.platform.imageStorage.${k}`, o);
  const { inputs, secrets, setField } = ctx;
  // '' is the default, the gateway.
  const provider = inputs.ImageStorageProvider || LOCAL;
  const [testing, setTesting] = useState(false);
  const [result, setResult] = useState(null);

  const test = async () => {
    setTesting(true);
    setResult(null);
    try {
      const res = await API.post('/api/option/image_storage/test', imageStorageTestPayload(inputs));
      const { success, message, data } = res.data;
      setResult(success ? { ok: true, url: data?.url } : { ok: false, message });
    } catch (e) {
      setResult({ ok: false, message: e.message });
    } finally {
      setTesting(false);
    }
  };

  const options = PROVIDERS.map((value) => ({ value, label: settingEnumLabel(t, PROVIDER_KEY, value) }));
  // An optional field says so after its catalog label; a unit written into a translated label
  // stays the input's suffix.
  const optionalLabel = (key) => {
    const { name, unit } = splitLabelUnit(settingLabel(t, key));
    return { label: s('optional', { label: name }), unit: unit || undefined };
  };

  return (
    <OptionCard
      ctx={ctx}
      id="image-storage"
      actions={
        provider !== OFF && (
          <div className="space-y-3">
            <div className="flex flex-wrap items-center gap-3">
              <Button type="button" variant="outline" size="sm" onClick={test} disabled={testing}>
                {testing ? <Loader2 className="size-4 animate-spin" /> : <ImageUp className="size-4" />}
                {s('test.button')}
              </Button>
              <span className="text-xs text-muted-foreground">{s('test.hint')}</span>
            </div>
            <UploadResult result={result} />
          </div>
        )
      }
    >
      <SelectRow
        id={PROVIDER_KEY}
        value={provider}
        onChange={(v) => {
          setField('ImageStorageProvider', v);
          setResult(null);
        }}
        options={options}
        description={provider === OFF ? undefined : settingEnumDescription(t, PROVIDER_KEY, provider)}
      />
      {provider === OFF && (
        <Alert variant="warning">
          <AlertDescription>{s('offNotice')}</AlertDescription>
        </Alert>
      )}
      {provider === LOCAL && (
        <p className="text-sm text-muted-foreground">
          {s('local.address', { address: inputs.ServerAddress || '—' })}{' '}
          <Link to={`${settingsGroupUrl('site')}?highlight=server-address`} className="text-primary hover:underline">
            {s('local.changeAddress')}
          </Link>
        </p>
      )}
      {provider !== OFF && <ToggleRow id="ImageStorageRehostUpstream" {...bindSwitch(ctx, 'ImageStorageRehostUpstream')} />}
      {FIELDS[provider] && (
        <div className="grid gap-5 sm:grid-cols-2">
          {(FIELDS[provider] || []).map(([key, field, required, secret]) => (
            <TextRow
              key={key}
              id={key}
              type={key === 'ImageStorageS3ExpirationDays' ? 'number' : undefined}
              {...(required ? {} : optionalLabel(key))}
              value={inputs[key]}
              onChange={(v) => setField(key, v)}
              placeholder={s(`fields.${field}.placeholder`, { defaultValue: '' }) || undefined}
              secret={secret ? secrets?.[key] : undefined}
            />
          ))}
        </div>
      )}
    </OptionCard>
  );
}

ImageStorageCard.propTypes = { ctx: PropTypes.object.isRequired };
